// Copies the white paper from ../business-docs (kept outside this repo) into the website.
//   pnpm sync:white-paper
// The page renders its own title and byline, so the doc's header block is dropped, and
// contact placeholders are replaced with a link to the partners page.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const src = `${root}../business-docs/LocalWorx_White_Paper.md`;
const out = `${root}apps/web/content/white-paper.md`;

let md = readFileSync(src, "utf8");
const body = md.indexOf("\n---\n");
if (body < 0) throw new Error("expected a --- after the header block");
md = md.slice(body + 5).replace(/^\s+/, "");
md = md.replace(/^\*\*Contact:\*\*.*$/m, "**Contact:** see [Founding partners](/partners).");
const leftover = md.match(/\[(npub|email)\]/);
if (leftover) throw new Error(`placeholder ${leftover[0]} would be published`);

writeFileSync(out, `<!-- Generated by scripts/sync-white-paper.mjs. Edit business-docs/LocalWorx_White_Paper.md instead. -->\n\n${md}`);
console.log(`wrote ${out.replace(root, "")}`);
